    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
    String cargo = Cargo.getSelectedItem().toString();
    String nome = txtNome.getText().trim();
    long cpf = Long.parseLong(txtCpf.getText().trim());
    int cod = Integer.parseInt(txtCod.getText().trim());
    int registro = Integer.parseInt(txtRegistro.getText().trim());

    if (nome.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Informe o nome!");
        return;
    }

    if (cargo.equals("Médico")) {
        TelaPrincipal.listaMedicos.add(new Medicos(cpf, nome, cod, registro));
    } else {
        TelaPrincipal.listaEnfermeiros.add(new Enfermeiros(cpf, nome, cod, registro));
    }

    atualizarTabela();
    txtNome.setText("");
    txtCpf.setText("");
    txtCod.setText("");
    txtRegistro.setText("");

    javax.swing.JOptionPane.showMessageDialog(this, cargo + " registrado com sucesso!");
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "CPF, Código e CRM/COREM devem conter apenas números!");
}
    }//GEN-LAST:event_jButton1ActionPerformed

