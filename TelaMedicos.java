    private void atualizarTabela() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabelaEquipe.getModel();
        modelo.setColumnIdentifiers(new Object[]{"Cargo", "Código", "Nome", "CPF", "Registro (CRM/COREM)"});
        modelo.setRowCount(0);

        for (Medicos m : TelaPrincipal.listaMedicos) {
            modelo.addRow(new Object[]{
                "Médico",
                m.getCodFuncionario(),
                m.getNome(),
                m.getCpf(),
                m.getCRM()
            });
        }

        for (Enfermeiros e : TelaPrincipal.listaEnfermeiros) {
            modelo.addRow(new Object[]{
                "Enfermeiro",
                e.getCodFuncionario(),
                e.getNome(),
                e.getCpf(),
                e.getCOREM()
            });
        }
    }
    
