    public void atualizarDashboard() {
        // 1. Cálculo de Quartos e Capacidade de Leitos
        int totalQuartos = listaQuartos.size();
        int disponiveis = 0;
        int lotados = 0;
        int capacidadeTotalLeitos = 0;
        int leitosOcupados = 0;

        for (Quartos q : listaQuartos) {
            q.checaDisponibilidade(); // Garante que o status disponível/lotado está sincronizado
            if (q.getDisponivel()) {
                disponiveis++;
            } else {
                lotados++;
            }
            capacidadeTotalLeitos += q.getLimitePessoas();
            leitosOcupados += q.getHospedes();
        }
        int leitosLivres = capacidadeTotalLeitos - leitosOcupados;

        labelTotalQuartos.setText(String.valueOf(totalQuartos));
        labelStatusQuartos.setText("Disponíveis: " + disponiveis);
        labelStatusQuartos2.setText("Lotados: " + lotados);

        // 2. Card Capacidade de Leitos
        labelTotalLeitos.setText(String.valueOf(capacidadeTotalLeitos));
        labelStatusLeitos.setText("Livres: " + leitosLivres);
        labelStatusLeitos2.setText("Ocupados: " + leitosOcupados);

        // 3. Card Médicos
        labelTotalMedicos.setText(String.valueOf(listaMedicos.size()));
        labelStatusMedicos.setText("Ativos: " + listaMedicos.size());
        labelStatusMedicos2.setText("Plantão: 0");

        // 4. Card Pacientes
        labelTotalPacientes.setText(String.valueOf(listaPacientes.size()));
        labelStatusPacientes.setText("Internados: " + listaPacientes.size());
        labelStatusPacientes2.setText("Alta: 0");

        // 5. Card Enfermeiros
        labelTotalEnfermeiros.setText(String.valueOf(listaEnfermeiros.size()));
        labelStatusEnfermeiros.setText("Ativos: " + listaEnfermeiros.size());
        labelStatusEnfermeiros2.setText("Plantão: 0");

        // 6. Card Equipe Geral
        int equipeGeral = listaMedicos.size() + listaEnfermeiros.size();
        labelTotalEquipe.setText(String.valueOf(equipeGeral));
        labelStatusEquipe.setText("Médicos: " + listaMedicos.size());
        labelStatusEquipe2.setText("Enfermeiros: " + listaEnfermeiros.size());
    }
    
